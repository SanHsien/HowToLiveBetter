// --- Taiwan localization overrides (Will, 2026-11-07) ---
// Entries whose substance is PRC law / PRC institutions are rewritten
// as advice for Taiwan readers (not word-swapped: procedures, agencies,
// fees and statutes are Taiwan's). The rewritten blocks live in
// scripts/zh-tw/localize/ and are listed in its index.json with the
// converted entry title each one replaces. Matching is by position
// (the Nth ### block) plus an exact title check, so if upstream edits
// or renumbers an entry the conversion fails loudly instead of
// silently localizing the wrong entry or dropping the rewrite on the
// next daily sync.
{
  const locDir = path.join(root, 'scripts/zh-tw/localize');
  const indexPath = path.join(locDir, 'index.json');
  if (fs.existsSync(indexPath)) {
    const index = JSON.parse(fs.readFileSync(indexPath, 'utf8'));
    let applied = 0;
    for (const item of index) {
      const target = path.join(root, item.file);
      if (!fs.existsSync(target)) throw new Error(`convert.mjs: localize target file missing: ${item.file}`);
      const override = fs.readFileSync(path.join(locDir, item.override), 'utf8').replace(/\s+$/, '');
      const text = fs.readFileSync(target, 'utf8');
      if (item.intro) {
        // Chapter intro override: replace everything before the first
        // entry heading, after checking the current intro still starts
        // with the expected text (upstream edits fail loudly).
        const firstHead = text.search(/^### /m);
        if (firstHead < 0) throw new Error(`convert.mjs: localize intro: no entries found in ${item.file}`);
        const introNow = text.slice(0, firstHead).replace(/\s+$/, '');
        const at = introNow.indexOf(item.expect);
        if (at < 0) throw new Error(`convert.mjs: localize intro mismatch in ${item.file}: expected intro to contain "${item.expect}" — upstream changed this intro; re-verify the Taiwan rewrite before updating the index`);
        fs.writeFileSync(target, introNow.slice(0, at) + override + '\n\n' + text.slice(firstHead));
        applied++;
        continue;
      }
      const heads = [...text.matchAll(/^### .*$/gm)];
      const h = heads[item.no - 1];
      if (!h) throw new Error(`convert.mjs: localize entry ${item.no} not found in ${item.file}`);
      const actualTitle = h[0].replace(/^### /, '');
      if (actualTitle !== item.title) throw new Error(`convert.mjs: localize title mismatch in ${item.file} #${item.no}: expected "${item.title}", found "${actualTitle}" — upstream changed this entry; re-verify the Taiwan rewrite before updating the index`);
      const start = h.index;
      const hasNext = item.no < heads.length;
      const end = hasNext ? heads[item.no].index : text.length;
      const next = text.slice(0, start) + override + (hasNext ? '\n\n' + text.slice(end) : '\n');
      fs.writeFileSync(target, next);
      applied++;
    }
    console.log(`localized ${applied} entries`);
  }
}

// Standalone docs (docs/*.md) whose entire content is China-specific get a
// full-document Taiwan replacement, kept in scripts/zh-tw/localize-docs/
// under the same file name. Applied after the entry overrides so edition
// edits targeting those files are superseded by the replacement. Each
// replacement must be a convertText fixed point (gate 4 verifies the tree).
{
  const docsDir = path.join(root, 'scripts/zh-tw/localize-docs');
  if (fs.existsSync(docsDir)) {
    let applied = 0;
    for (const name of fs.readdirSync(docsDir).sort()) {
      if (!name.endsWith('.md')) continue;
      const target = path.join(root, 'docs', name);
      if (!fs.existsSync(target)) throw new Error(`convert.mjs: localize-docs target missing: docs/${name}`);
      fs.writeFileSync(target, fs.readFileSync(path.join(docsDir, name), 'utf8'));
      applied++;
    }
    console.log(`localized ${applied} docs`);
  }
}

