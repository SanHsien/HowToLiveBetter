// og.png itself is re-rendered by regen-images.mjs from the updated
// og.html, so the screenshot step is skipped here. sync-stats also
// re-runs updates.mjs from local git history; the edition keeps the
// upstream per-entry dates instead (see the book.yml note), so
// updates.json is snapshotted and restored around the call.
{
  const updatesPath = path.join(root, 'updates.json');
  const updatesSnapshot = fs.readFileSync(updatesPath, 'utf8');
  execFileSync('node', ['tools/sync-stats.mjs', '--no-screenshot'], { cwd: root, stdio: 'inherit' });
  fs.writeFileSync(updatesPath, updatesSnapshot);
}
